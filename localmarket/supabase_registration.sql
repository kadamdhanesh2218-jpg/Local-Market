-- Run this SQL in your Supabase SQL Editor if you want to store registrations in your Supabase database:

create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  address text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable Row Level Security
alter table public.registrations enable row level security;

-- Allow anonymous inserts (for customer registration from the website)
create policy "Allow anonymous registrations"
  on public.registrations
  for insert
  to anon
  with check (true);

-- Allow anonymous reads
create policy "Allow reading registrations"
  on public.registrations
  for select
  to anon
  using (true);
